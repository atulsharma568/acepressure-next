-- PostgreSQL 14+ baseline for AcePressure 1.6.7 (SQLite migrations 001-009).
-- Run via apply.sql or scripts/migrate_sqlite_to_postgres.py, never the SQLite runner.
-- Money and UTC epoch seconds remain signed 64-bit integers. JSON-shaped text
-- is validated into JSONB; ordinary historical text columns remain TEXT.
DO $$
BEGIN
    IF current_schema() NOT IN ('acepressure_shadow', 'acepressure_import')
       OR current_schema() IS NULL THEN
        RAISE EXCEPTION 'Select the dedicated AcePressure shadow/import schema first';
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS _postgres_migrations (
    version INTEGER PRIMARY KEY,
    name TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS settings (
    key TEXT COLLATE "C" PRIMARY KEY,
    value JSONB NOT NULL
);

CREATE TABLE IF NOT EXISTS supporters (
    id TEXT COLLATE "C" PRIMARY KEY,
    identity_hash TEXT COLLATE "C" UNIQUE NOT NULL,
    email TEXT,
    name TEXT NOT NULL,
    blocked BOOLEAN NOT NULL DEFAULT FALSE,
    muted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS sessions (
    id TEXT COLLATE "C" PRIMARY KEY,
    title TEXT NOT NULL,
    started BIGINT NOT NULL,
    ended BIGINT
);
CREATE UNIQUE INDEX IF NOT EXISTS one_active_session ON sessions ((1)) WHERE ended IS NULL;

CREATE TABLE IF NOT EXISTS soundboards (
    id TEXT COLLATE "C" PRIMARY KEY,
    name TEXT NOT NULL,
    emoji TEXT NOT NULL DEFAULT '',
    media_filename TEXT,
    category TEXT NOT NULL DEFAULT 'General',
    min_paise BIGINT NOT NULL DEFAULT 0 CHECK (min_paise >= 0),
    display_order BIGINT NOT NULL DEFAULT 0,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    duration_ms BIGINT DEFAULT 0,
    created BIGINT NOT NULL,
    volume SMALLINT NOT NULL DEFAULT 100 CHECK (volume BETWEEN 10 AND 100)
);
CREATE INDEX IF NOT EXISTS soundboards_enabled_order ON soundboards (enabled, display_order);
CREATE INDEX IF NOT EXISTS soundboards_category ON soundboards (category);

CREATE TABLE IF NOT EXISTS tips (
    id TEXT COLLATE "C" PRIMARY KEY,
    token TEXT COLLATE "C" UNIQUE NOT NULL,
    supporter_id TEXT COLLATE "C" NOT NULL REFERENCES supporters (id),
    name TEXT NOT NULL,
    display_paise BIGINT NOT NULL CHECK (display_paise > 0),
    requested_paise BIGINT NOT NULL,
    actual_paise BIGINT,
    message TEXT NOT NULL,
    created BIGINT NOT NULL,
    expires BIGINT NOT NULL,
    verified BIGINT,
    session_id TEXT COLLATE "C" REFERENCES sessions (id),
    reference TEXT COLLATE "C" UNIQUE,
    status TEXT NOT NULL CHECK (status IN ('PENDING','VERIFIED','EXPIRED','REFUNDED','MANUAL','REJECTED')),
    tts BOOLEAN NOT NULL,
    voice TEXT NOT NULL,
    sound TEXT NOT NULL,
    alert_shown BOOLEAN DEFAULT FALSE,
    tts_played BOOLEAN DEFAULT FALSE,
    verification_source TEXT,
    note TEXT DEFAULT '',
    soundboard_id TEXT COLLATE "C" REFERENCES soundboards (id)
);
CREATE INDEX IF NOT EXISTS tips_match ON tips (requested_paise, status, expires);
CREATE INDEX IF NOT EXISTS tips_time ON tips (verified, status);
CREATE INDEX IF NOT EXISTS tips_supporter ON tips (supporter_id);
CREATE INDEX IF NOT EXISTS tips_session ON tips (session_id);
CREATE INDEX IF NOT EXISTS tips_soundboard ON tips (soundboard_id);

-- Historical soft associations remain TEXT, as in SQLite. Do not invent or
-- silently repair ledger links by adding new foreign keys during an import.
CREATE TABLE IF NOT EXISTS receipts (
    reference TEXT COLLATE "C" PRIMARY KEY,
    amount BIGINT NOT NULL,
    received BIGINT NOT NULL,
    ingested BIGINT NOT NULL,
    outcome TEXT NOT NULL,
    tip_id TEXT
);
CREATE INDEX IF NOT EXISTS receipts_tip ON receipts (tip_id);

CREATE TABLE IF NOT EXISTS amount_leases (
    amount BIGINT PRIMARY KEY,
    until BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS amount_leases_until ON amount_leases (until);

CREATE TABLE IF NOT EXISTS goals (
    id TEXT COLLATE "C" PRIMARY KEY,
    title TEXT NOT NULL,
    target BIGINT NOT NULL CHECK (target > 0),
    starting BIGINT NOT NULL DEFAULT 0,
    period TEXT NOT NULL,
    reset TEXT NOT NULL,
    starts BIGINT,
    ends BIGINT,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    design TEXT NOT NULL,
    style TEXT NOT NULL,
    session_id TEXT
);
CREATE INDEX IF NOT EXISTS goals_session ON goals (session_id);

CREATE TABLE IF NOT EXISTS alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tip_id TEXT COLLATE "C" REFERENCES tips (id),
    payload JSONB NOT NULL,
    created BIGINT NOT NULL,
    expires BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS alerts_tip ON alerts (tip_id);
CREATE INDEX IF NOT EXISTS alerts_expires ON alerts (expires);

CREATE TABLE IF NOT EXISTS deliveries (
    alert_id BIGINT NOT NULL REFERENCES alerts (id),
    channel TEXT COLLATE "C" NOT NULL CHECK (channel IN ('horizontal','vertical')),
    state TEXT NOT NULL DEFAULT 'queued'
        CHECK (state IN ('queued','playing','done','cancelled','expired','skipped')),
    owner TEXT,
    lease BIGINT,
    PRIMARY KEY (alert_id, channel)
);
CREATE INDEX IF NOT EXISTS deliveries_queue ON deliveries (channel, state, alert_id);
CREATE INDEX IF NOT EXISTS deliveries_lease ON deliveries (lease) WHERE state = 'playing';

CREATE TABLE IF NOT EXISTS audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at BIGINT NOT NULL,
    actor TEXT NOT NULL,
    action TEXT NOT NULL,
    object_id TEXT,
    detail JSONB NOT NULL
);

CREATE TABLE IF NOT EXISTS rate_limits (
    bucket TEXT COLLATE "C" PRIMARY KEY,
    count BIGINT NOT NULL CHECK (count >= 0),
    until BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS rate_limits_until ON rate_limits (until);

-- This is copied verbatim from SQLite, NOT used to version the PostgreSQL DDL.
CREATE TABLE IF NOT EXISTS schema_version (version BIGINT PRIMARY KEY);

CREATE TABLE IF NOT EXISTS paytm_captures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fingerprint TEXT COLLATE "C" UNIQUE NOT NULL,
    captured_at BIGINT NOT NULL,
    amount_paise BIGINT,
    outcome TEXT NOT NULL,
    repeats BIGINT NOT NULL DEFAULT 0 CHECK (repeats >= 0)
);

CREATE TABLE IF NOT EXISTS paytm_events (
    fingerprint TEXT COLLATE "C" PRIMARY KEY,
    ingested BIGINT NOT NULL,
    amount_paise BIGINT,
    outcome TEXT NOT NULL,
    tip_id TEXT,
    repeats BIGINT NOT NULL DEFAULT 0 CHECK (repeats >= 0)
);

CREATE TABLE IF NOT EXISTS paytm_bridge (
    id BIGINT PRIMARY KEY CHECK (id = 1),
    token_hash TEXT NOT NULL DEFAULT '',
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    auto_match BOOLEAN NOT NULL DEFAULT FALSE,
    recipient_hash TEXT NOT NULL DEFAULT '',
    last_seen BIGINT
);

CREATE TABLE IF NOT EXISTS paytm_inbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fingerprint TEXT COLLATE "C" UNIQUE NOT NULL,
    received BIGINT NOT NULL,
    payment_minute BIGINT,
    amount BIGINT,
    status TEXT NOT NULL,
    reason TEXT NOT NULL,
    tip_id TEXT,
    candidates JSONB NOT NULL DEFAULT '[]'::jsonb,
    repeats BIGINT NOT NULL DEFAULT 0 CHECK (repeats >= 0)
);
CREATE INDEX IF NOT EXISTS paytm_inbox_review ON paytm_inbox (status, received);
CREATE INDEX IF NOT EXISTS paytm_inbox_tip ON paytm_inbox (tip_id);

CREATE TABLE IF NOT EXISTS supporter_aliases (
    source_id TEXT COLLATE "C" PRIMARY KEY REFERENCES supporters (id),
    target_id TEXT COLLATE "C" NOT NULL REFERENCES supporters (id),
    CHECK (source_id <> target_id)
);
CREATE INDEX IF NOT EXISTS supporter_aliases_target ON supporter_aliases (target_id);

CREATE TABLE IF NOT EXISTS browser_supporters (
    token_hash TEXT COLLATE "C" PRIMARY KEY,
    supporter_id TEXT COLLATE "C" NOT NULL REFERENCES supporters (id),
    expires BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS browser_supporters_supporter ON browser_supporters (supporter_id);
CREATE INDEX IF NOT EXISTS browser_supporters_expires ON browser_supporters (expires);

-- register_tts creates this outside the SQLite SQL migrations. Older backups
-- may omit it, in which case its PostgreSQL counterpart remains empty.
CREATE TABLE IF NOT EXISTS tts_health (
    id BIGINT PRIMARY KEY CHECK (id = 1),
    code TEXT,
    at BIGINT
);

INSERT INTO _postgres_migrations (version, name)
VALUES (1, 'AcePressure 1.6.7 shadow baseline; SQLite 001-009')
ON CONFLICT (version) DO NOTHING;
